"""
Extensible Quantum Chemistry (QM) Input File Generator Architecture.

Designed as an extensible provider-based system so any QM package
(Gaussian, ORCA, xTB, PySCF, openLOWDIN, Q-Chem, NWChem, GAMESS, etc.)
can be registered seamlessly with its own options, syntax, and file extensions.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import List, Dict, Optional, Type
import numpy as np

from .zmatrix import ZAtom, format_zmatrix_numeric, format_zmatrix_variables


@dataclass
class QMCalculationParameters:
    """Standardized parameters shared across all QM codes."""
    job_type: str = "Opt + Freq"         # "SP", "Opt", "Freq", "Opt + Freq", "TS"
    method: str = "B3LYP"                # Functional or wavefunction method
    basis: str = "def2-SVP"              # Basis set
    charge: int = 0                      # Net molecular charge
    multiplicity: int = 1                # Spin multiplicity (2S + 1)
    solvent: str = "None (Gas Phase)"    # Solvent name
    n_procs: int = 8                     # CPU threads / cores
    memory_gb: int = 16                  # RAM in Gigabytes
    dispersion: str = "D3BJ"             # Dispersion correction (e.g. D3BJ, D4, none)
    title: str = "Generated by AgyMolden"
    chk_file: str = "calculation.chk"
    use_zmatrix: bool = False            # True for internal coordinates if supported
    extra_keywords: str = ""             # Custom user-added keywords or flags
    frozen_atoms: List[int] = field(default_factory=list) # 0-based atom indices frozen in optimization
    scan_spec: Optional[Tuple[str, List[int], float, float, int]] = None  # ("B"|"A"|"D", 0-based indices, start, end, steps)


COMMON_METHODS = [
    "B3LYP", "PBE0", "wB97X-D", "M06-2X", "CAM-B3LYP", "B97D3", "HF", "MP2", "CCSD(T)", "GFN2-xTB"
]

COMMON_BASIS_SETS = [
    "def2-SVP", "def2-TZVP", "def2-QZVP", "6-31G*", "6-31+G(d,p)", "6-311++G(d,p)", "cc-pVDZ", "cc-pVTZ", "sto-3g"
]

COMMON_SOLVENTS = [
    "None (Gas Phase)", "Water", "Acetonitrile", "Chloroform", "Dichloromethane (DCM)",
    "DMSO", "Ethanol", "Methanol", "THF", "Toluene"
]


class BaseQMGenerator(ABC):
    """Abstract base class for all QM calculation input generators."""
    code_name: str = "Generic QM"
    file_extension: str = ".inp"
    supports_zmatrix: bool = False
    supported_methods: List[str] = COMMON_METHODS
    supported_basis_sets: List[str] = COMMON_BASIS_SETS

    @abstractmethod
    def generate_input(
        self,
        symbols: List[str],
        coords: np.ndarray,
        params: QMCalculationParameters,
        zatoms: Optional[List[ZAtom]] = None,
        variables: Optional[Dict[str, float]] = None,
    ) -> str:
        """Return the formatted input file content as a string."""
        pass


class GaussianGenerator(BaseQMGenerator):
    code_name = "Gaussian (09/16)"
    file_extension = ".gjf"
    supports_zmatrix = True

    SOLVENT_MAP = {
        "Water": "water", "Acetonitrile": "acetonitrile", "Chloroform": "chloroform",
        "Dichloromethane (DCM)": "dichloromethane", "DMSO": "dmso", "Ethanol": "ethanol",
        "Methanol": "methanol", "THF": "thf", "Toluene": "toluene"
    }

    def generate_input(self, symbols, coords, params, zatoms=None, variables=None) -> str:
        lines = [
            f"%chk={params.chk_file}",
            f"%nprocshared={params.n_procs}",
            f"%mem={params.memory_gb}GB",
        ]
        job_keys = []
        if "Opt" in params.job_type:
            job_keys.append("opt")
        if "Freq" in params.job_type:
            job_keys.append("freq")
        if "SP" in params.job_type or not job_keys:
            job_keys.append("sp")
        if "TS" in params.job_type:
            job_keys.append("opt=(ts,calcfc,noeigentest)")

        func = params.method.split()[0]
        if params.frozen_atoms or params.scan_spec:
            # Gaussian modredundant option
            job_keys = [k if k != "opt" else "opt=modredundant" for k in job_keys]
            if "opt" not in " ".join(job_keys):
                job_keys.append("opt=modredundant")

        route = f"#p {func}/{params.basis} {' '.join(job_keys)}"
        if params.solvent != "None (Gas Phase)" and params.solvent in self.SOLVENT_MAP:
            route += f" scrf=(cpcm,solvent={self.SOLVENT_MAP[params.solvent]})"
        if params.extra_keywords.strip():
            route += f" {params.extra_keywords.strip()}"

        lines.append(route)
        lines.append("")
        lines.append(params.title)
        lines.append("")
        lines.append(f"{params.charge} {params.multiplicity}")

        if params.use_zmatrix and zatoms:
            zmat_str = format_zmatrix_variables(zatoms, variables) if variables else format_zmatrix_numeric(zatoms)
            lines.append(zmat_str)
        else:
            for s, (x, y, z) in zip(symbols, coords):
                lines.append(f" {s:<2}  {x:12.6f} {y:12.6f} {z:12.6f}")

        # Inject Gaussian modredundant freeze / scan specifications
        if params.frozen_atoms or params.scan_spec:
            lines.append("")
            for idx in params.frozen_atoms:
                lines.append(f"X {idx+1} F")
            if params.scan_spec:
                stype, s_indices, s_start, s_end, s_steps = params.scan_spec
                n_intervals = max(1, int(s_steps) - 1)
                step_size = (float(s_end) - float(s_start)) / n_intervals
                idx_1based = " ".join(str(i + 1) for i in s_indices)
                lines.append(f"{stype} {idx_1based} S {n_intervals} {step_size:.4f}")

        lines.append("")
        return "\n".join(lines)


class OrcaGenerator(BaseQMGenerator):
    code_name = "ORCA (5.x/6.x)"
    file_extension = ".inp"
    supports_zmatrix = False

    SOLVENT_MAP = {
        "Water": "Water", "Acetonitrile": "Acetonitrile", "Chloroform": "Chloroform",
        "Dichloromethane (DCM)": "CH2Cl2", "DMSO": "DMSO", "Ethanol": "Ethanol",
        "Methanol": "Methanol", "THF": "THF", "Toluene": "Toluene"
    }

    def generate_input(self, symbols, coords, params, zatoms=None, variables=None) -> str:
        lines = [f"# {params.title}"]
        job_keys = []
        if "Opt" in params.job_type:
            job_keys.append("Opt")
        if "Freq" in params.job_type:
            job_keys.append("Freq")
        if "SP" in params.job_type or not job_keys:
            job_keys.append("SP")
        if "TS" in params.job_type:
            job_keys.append("OptTS")

        func = params.method.split()[0]
        simple_route = f"! {func} {params.basis}"
        if params.dispersion and params.dispersion != "None":
            simple_route += f" {params.dispersion}"
        if job_keys:
            simple_route += " " + " ".join(job_keys)
        if params.solvent != "None (Gas Phase)" and params.solvent in self.SOLVENT_MAP:
            simple_route += f" CPCM({self.SOLVENT_MAP[params.solvent]})"
        if params.extra_keywords.strip():
            simple_route += f" {params.extra_keywords.strip()}"

        lines.append(simple_route)
        if params.n_procs > 1:
            lines.append(f"%pal nprocs {params.n_procs} end")
        lines.append(f"%maxcore {int(params.memory_gb * 1024 / max(1, params.n_procs))}")

        # Inject ORCA Constraints / Relaxed Surface Scan if frozen atoms or scan_spec exist
        if params.frozen_atoms or params.scan_spec:
            lines.append("%geom")
            if params.frozen_atoms:
                lines.append("  Constraints")
                for idx in params.frozen_atoms:
                    lines.append(f"    {{ C {idx} C }}")
                lines.append("  end")
            if params.scan_spec:
                stype, s_indices, s_start, s_end, s_steps = params.scan_spec
                idx_str = " ".join(str(i) for i in s_indices)
                lines.append("  Scan")
                lines.append(f"    {stype} {idx_str} = {float(s_start):.3f}, {float(s_end):.3f}, {max(2, int(s_steps))}")
                lines.append("  end")
            lines.append("end")

        lines.append("")
        lines.append(f"* xyz {params.charge} {params.multiplicity}")
        for s, (x, y, z) in zip(symbols, coords):
            lines.append(f"  {s:<2}  {x:12.6f} {y:12.6f} {z:12.6f}")
        lines.append("*")
        lines.append("")
        return "\n".join(lines)


class PySCFGenerator(BaseQMGenerator):
    code_name = "PySCF (Python Script)"
    file_extension = ".py"
    supports_zmatrix = False

    SOLVENT_MAP = {
        "Water": "water", "Acetonitrile": "acetonitrile", "Chloroform": "chloroform",
        "Dichloromethane (DCM)": "dichloromethane", "DMSO": "dmso", "Ethanol": "ethanol",
        "Methanol": "methanol", "THF": "thf", "Toluene": "toluene"
    }

    def generate_input(self, symbols, coords, params, zatoms=None, variables=None) -> str:
        atom_entries = []
        for s, (x, y, z) in zip(symbols, coords):
            atom_entries.append(f"        '{s} {x:.6f} {y:.6f} {z:.6f}'")
        geom_str = ";\n".join(atom_entries)

        spin = params.multiplicity - 1
        method_upper = params.method.strip().upper()
        func = params.method.lower().replace("-", "")

        lines = [
            '#!/usr/bin/env python3',
            f'"""{params.title} - Generated by AgyMolden"""',
            'import numpy as np',
            'from pyscf import gto, scf, dft, lib',
            '',
            f'# Set thread limit',
            f'lib.num_threads({params.n_procs})',
            '',
            '# Build molecule',
            'mol = gto.Mole()',
            'mol.atom = """',
            geom_str,
            '"""',
            f'mol.basis = "{params.basis}"',
            f'mol.charge = {params.charge}',
            f'mol.spin = {spin}  # 2S = multiplicity - 1',
            f'mol.max_memory = {params.memory_gb * 1000}  # MB',
            'mol.verbose = 4  # 4=Detailed SCF cycles & MO energies, 5=Full AO/MO coefficients & population',
            'mol.build()',
            '',
            f'# Calculation: {params.method}',
        ]

        # Determine SCF type (DFT vs HF)
        is_dft = any(k in func for k in ["b3lyp", "pbe", "m06", "wb97", "b97", "scan", "blyp", "tpss"])
        if is_dft:
            if spin == 0:
                lines.append('mf = dft.RKS(mol)')
            else:
                lines.append('mf = dft.UKS(mol)')
            lines.append(f'mf.xc = "{params.method}"')
        else:
            if spin == 0:
                lines.append('mf = scf.RHF(mol)')
            else:
                lines.append('mf = scf.UHF(mol)')

        # Dispersion correction (DFT-D3 / D3BJ)
        disp_lower = (params.dispersion or "").lower()
        if "d3" in disp_lower:
            disp_tag = "d3bj" if "bj" in disp_lower or "d3bj" in disp_lower else "d3zero"
            lines.append(f'try:')
            lines.append(f'    mf.disp = "{disp_tag}"')
            lines.append(f'except Exception:')
            lines.append(f'    pass  # disp requires pyscf-dispersion or dftd3')

        # Implicit Solvation
        solv_key = self.SOLVENT_MAP.get(params.solvent)
        if solv_key:
            lines.extend([
                f'# Implicit Solvation: {params.solvent}',
                f'try:',
                f'    from pyscf.solvent import ddcosmo',
                f'    mf = ddcosmo.DDCOSMO(mf)',
                f'    mf.with_solvent.eps = ddcosmo.get_solvent("{solv_key}")',
                f'except Exception as e_solv:',
                f'    print(f"Solvation warning: {{e_solv}}")',
            ])

        # Density Fitting for speed and larger basis sets
        lines.append('mf = mf.density_fit()')

        # Run SCF
        lines.append('mf.kernel()')
        lines.append('mf.analyze(verbose=4)  # Print Mulliken population, dipole moment & MO summary')
        lines.append('print("SCF Total Energy:", mf.e_tot)')
        lines.append('')

        # Correlated post-HF methods
        if "MP2" in method_upper:
            lines.extend([
                '# MP2 Correlation Energy',
                'from pyscf import mp',
                'mp2 = mp.MP2(mf).run()',
                'print("MP2 Correlation Energy:", mp2.e_corr)',
                'print("MP2 Total Energy:", mp2.e_tot)',
                '',
            ])
        elif "CCSD(T)" in method_upper:
            lines.extend([
                '# CCSD(T) Coupled Cluster',
                'from pyscf import cc',
                'mycc = cc.CCSD(mf).run()',
                'et = mycc.ccsd_t()',
                'print("CCSD Correlation Energy:", mycc.e_corr)',
                'print("CCSD Total Energy:", mycc.e_tot)',
                'print("(T) Energy Correction:", et)',
                'print("CCSD(T) Total Energy:", mycc.e_tot + et)',
                '',
            ])
        elif "CCSD" in method_upper:
            lines.extend([
                '# CCSD Coupled Cluster',
                'from pyscf import cc',
                'mycc = cc.CCSD(mf).run()',
                'print("CCSD Correlation Energy:", mycc.e_corr)',
                'print("CCSD Total Energy:", mycc.e_tot)',
                '',
            ])

        # Geometry Optimization
        if "Opt" in params.job_type:
            if params.scan_spec:
                stype, s_indices, s_start, s_end, s_steps = params.scan_spec
                kw = {"B": "distance", "A": "angle", "D": "dihedral"}.get(stype, "distance")
                idx_1based = " ".join(str(i + 1) for i in s_indices)
                lines.extend([
                    '# Relaxed Potential Energy Surface Scan via geomeTRIC constraints',
                    'try:',
                    '    import tempfile',
                    '    from pyscf.geomopt.geometric_solver import optimize',
                    f'    scan_txt = "$scan\\n{kw} {idx_1based} {float(s_start):.4f} {float(s_end):.4f} {max(2, int(s_steps))}\\n"',
                    '    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as tf:',
                    '        tf.write(scan_txt)',
                    '        c_path = tf.name',
                    '    mol_eq = optimize(mf, constraints=c_path)',
                    '    print("Completed Relaxed PES Scan.")',
                    'except Exception as e_scan:',
                    '    print("PySCF scan error (install geometric):", e_scan)',
                    '',
                ])
            else:
                lines.extend([
                    '# Geometry Optimization via geometric or berny',
                    'try:',
                    '    from pyscf.geomopt.geometric_solver import optimize',
                    '    mol_eq = optimize(mf)',
                    '    print("Optimized Coordinates:")',
                    '    print(mol_eq.tostring(format="xyz"))',
                    'except ImportError:',
                    '    print("Install geometric: pip install geometric for PySCF geometry optimization.")',
                    '',
                ])

        # Harmonic Frequencies
        if "Freq" in params.job_type:
            lines.extend([
                '# Harmonic Vibrational Frequencies & Normal Modes',
                'try:',
                '    from pyscf.hessian import thermo',
                '    hessian = mf.Hessian().kernel()',
                '    freq_info = thermo.harmonic_analysis(mf.mol, hessian)',
                '    thermo.dump_normal_mode(mf.mol, freq_info)',
                '    thermo_info = thermo.thermo(mf, freq_info["freq_au"], 298.15, 101325)',
                '    thermo.dump_thermo(mf.mol, thermo_info)',
                '    print("Frequencies (cm-1):", freq_info["freq_wavenumber"])',
                'except Exception as err:',
                '    print("Hessian calculation error:", err)',
                '',
            ])

        # Export Orbitals & Density for AgyMolden Visualization
        lines.extend([
            '# Export Molden orbitals & electron density for AgyMolden visualization',
            'try:',
            '    from pyscf.tools import molden, cubegen',
            '    molden.from_mo(mol, "orbitals.molden", mf.mo_coeff)',
            '    cubegen.density(mol, "electron_density.cube", mf.make_rdm1())',
            '    print("Exported orbitals.molden and electron_density.cube successfully.")',
            'except Exception as err_export:',
            '    print(f"Molden/Cube export warning: {err_export}")',
            '',
        ])

        return "\n".join(lines)


class OpenLOWDINGenerator(BaseQMGenerator):
    """
    openLOWDIN Multi-Component Quantum Chemistry & APMO Input Generator.
    
    Generates native openLOWDIN .lowdin inputs consisting of:
    - SYSTEM_DESCRIPTION
    - GEOMETRY ... END GEOMETRY with quantum species e-(Symbol) and classical nuclei Symbol dirac
    - TASKS ... END TASKS with method (RHF, UHF, RKS, UKS) and task flags
    - CONTROL ... END CONTROL with solver and convergence controls
    - OUTPUTS ... END OUTPUTS requesting moldenFile, density outputs, etc.
    """
    code_name = "openLOWDIN (APMO / Quantum Chemistry)"
    file_extension = ".lowdin"
    supports_zmatrix = False

    # Standard basis sets well-supported by openLOWDIN library
    supported_basis_sets = [
        "STO-3G", "3-21G", "6-31G", "6-31G*", "6-311G", "6-311G*",
        "CC-PVDZ", "CC-PVTZ", "CC-PVQZ",
        "AUG-CC-PVDZ", "AUG-CC-PVTZ", "AUG-CC-PVQZ",
        "DEF2-SVP", "DEF2-TZVP", "DEF2-QZVP",
    ]

    # Map general basis names to openLOWDIN basis library conventions
    BASIS_MAP = {
        "sto-3g": "STO-3G",
        "3-21g": "3-21G",
        "6-31g": "6-31G",
        "6-31g*": "6-31G.D",
        "6-31g(d)": "6-31G.D",
        "6-31g(d,p)": "6-31G.D.P",
        "6-31+g(d,p)": "6-31+G.D.P",
        "6-31++g(d,p)": "6-31++G.D.P",
        "6-311g": "6-311G",
        "6-311g*": "6-311G.D",
        "6-311g(d)": "6-311G.D",
        "6-311g(d,p)": "6-311G.D.P",
        "6-311++g(d,p)": "6-311++G.D.P",
        "cc-pvdz": "CC-PVDZ",
        "cc-pvtz": "CC-PVTZ",
        "cc-pvqz": "CC-PVQZ",
        "aug-cc-pvdz": "AUG-CC-PVDZ",
        "aug-cc-pvtz": "AUG-CC-PVTZ",
        "aug-cc-pvqz": "AUG-CC-PVQZ",
        "def2-svp": "DEF2-SVP",
        "def2-tzvp": "DEF2-TZVP",
        "def2-qzvp": "DEF2-QZVP",
    }

    # Dielectric constants for COSMO in openLOWDIN
    COSMO_DIELECTRICS = {
        "Water": 78.3553,
        "Acetonitrile": 36.64,
        "Methanol": 32.61,
        "Ethanol": 24.55,
        "DMSO": 46.7,
        "Dichloromethane (DCM)": 8.93,
        "THF": 7.58,
        "Chloroform": 4.81,
        "Toluene": 2.38,
    }

    def generate_input(self, symbols, coords, params, zatoms=None, variables=None) -> str:
        lines = [
            f"SYSTEM_DESCRIPTION='{params.title}'",
            "",
            "GEOMETRY",
        ]

        # Determine basis set tag for openLOWDIN
        basis_raw = params.basis.strip().lower()
        lowdin_basis = self.BASIS_MAP.get(basis_raw, params.basis.upper())

        is_open_shell = (params.multiplicity != 1)

        # 1. Quantum electron carriers: e-(Element)
        # Handle net molecular charge via addParticles on the first atom if nonzero
        for idx, (s, (x, y, z)) in enumerate(zip(symbols, coords)):
            extra_part = ""
            if idx == 0 and params.charge != 0:
                # In openLOWDIN: electron particle count change = -charge (negative charge = more electrons)
                extra_part = f" addParticles={-params.charge}"
            lines.append(f"\te-({s.strip()})   {lowdin_basis:<12} {x:12.6f} {y:12.6f} {z:12.6f}{extra_part}")

        # 2. Classical nuclei: Symbol dirac
        for s, (x, y, z) in zip(symbols, coords):
            lines.append(f"\t{s:<5}   dirac        {x:12.6f} {y:12.6f} {z:12.6f}")

        lines.append("END GEOMETRY")
        lines.append("")

        # TASKS block
        lines.append("TASKS")
        m_upper = params.method.upper()
        is_dft = any(dft_kw in m_upper for dft_kw in ["B3LYP", "PBE", "BLYP", "M06", "CAM-B3LYP", "WB97"])

        if is_open_shell:
            method_str = "UKS" if is_dft else "UHF"
        else:
            method_str = "RKS" if is_dft else "RHF"

        lines.append(f"\tmethod = \"{method_str}\"")

        # MP2 Moller-Plesset task
        if "MP2" in m_upper:
            lines.append("\tmollerPlessetCorrection = 2")

        # Geometry optimization task
        if "Opt" in params.job_type:
            lines.append("\toptimizeGeometry = .true.")

        # COSMO Solvation task
        use_cosmo = (params.solvent != "None (Gas Phase)")
        if use_cosmo:
            lines.append("\tcosmo = .true.")

        lines.append("END TASKS")
        lines.append("")

        # CONTROL block
        lines.append("CONTROL")
        lines.append("\treadCoefficients = .false.")

        if is_dft:
            func = params.method.split()[0].upper()
            lines.append(f"\telectronExchangeCorrelationFunctional = \"{func}\"")

        if use_cosmo:
            dielectric = self.COSMO_DIELECTRICS.get(params.solvent, 78.3553)
            lines.append(f"\tcosmo_solvent_dielectric = {dielectric:.4f}")

        if "Opt" in params.job_type or "Freq" in params.job_type:
            lines.append("\tgetGradients = .true.")

        if params.extra_keywords.strip():
            for kw in params.extra_keywords.splitlines():
                if kw.strip():
                    lines.append(f"\t{kw.strip()}")

        lines.append("END CONTROL")
        lines.append("")

        # OUTPUTS block
        lines.append("OUTPUTS")
        lines.append("\tmoldenFile")
        lines.append("END OUTPUTS")
        lines.append("")

        return "\n".join(lines)


class XTBGenerator(BaseQMGenerator):
    code_name = "xTB (Tight-Binding)"
    file_extension = ".sh"
    supports_zmatrix = False

    SOLVENT_MAP = {
        "Water": "water", "Acetonitrile": "acetonitrile", "Chloroform": "chloroform",
        "Dichloromethane (DCM)": "ch2cl2", "DMSO": "dmso", "Ethanol": "ethanol",
        "Methanol": "methanol", "THF": "thf", "Toluene": "toluene"
    }

    def generate_input(self, symbols, coords, params, zatoms=None, variables=None) -> str:
        opts = ["xtb structure.xyz", "--gfn 2"]
        if params.charge != 0:
            opts.append(f"--chrg {params.charge}")
        uhf = params.multiplicity - 1
        if uhf != 0:
            opts.append(f"--uhf {uhf}")
        if "Opt" in params.job_type:
            opts.append("--opt")
        if "Freq" in params.job_type:
            opts.append("--hess")
        if params.solvent != "None (Gas Phase)" and params.solvent in self.SOLVENT_MAP:
            opts.append(f"--alpb {self.SOLVENT_MAP[params.solvent]}")
        if params.extra_keywords.strip():
            opts.append(params.extra_keywords.strip())

        cmd = " ".join(opts)
        return (
            "#!/usr/bin/env bash\n"
            f"# {params.title}\n"
            f"# Requires: structure.xyz in the working directory\n\n"
            f"export OMP_NUM_THREADS={params.n_procs}\n"
            f"export MKL_NUM_THREADS={params.n_procs}\n"
            f"{cmd}\n"
        )


class QChemGenerator(BaseQMGenerator):
    code_name = "Q-Chem"
    file_extension = ".in"
    supports_zmatrix = False

    def generate_input(self, symbols, coords, params, zatoms=None, variables=None) -> str:
        lines = [
            f"# {params.title}",
            "$rem",
            f"   jobtype      {'opt' if 'Opt' in params.job_type else 'sp'}",
            f"   method       {params.method}",
            f"   basis        {params.basis}",
        ]
        if "Freq" in params.job_type:
            lines.append("   vibman_print 2")
        if params.extra_keywords.strip():
            lines.append(f"   {params.extra_keywords.strip()}")
        lines.append("$end")
        lines.append("")
        lines.append("$molecule")
        lines.append(f"   {params.charge} {params.multiplicity}")
        for s, (x, y, z) in zip(symbols, coords):
            lines.append(f"   {s:<2}  {x:12.6f} {y:12.6f} {z:12.6f}")
        lines.append("$end")
        lines.append("")
        return "\n".join(lines)


