"""
Reproducibility Bundle Exporter for AgyMolden.

Packages complete quantum chemistry calculation data into a single Supporting Information (SI)
archive (.zip) containing:
1. GEOMETRY.xyz (Standard Cartesian coordinates with SI header)
2. GEOMETRY.zmat (Standard internal Z-matrix coordinates)
3. CALCULATION_SUMMARY.json (Machine-readable energetic, thermochemical, and orbital data)
4. COMPUTATIONAL_DETAILS.md (Publication-ready Methods section paragraph and coordinate tables)
5. Raw input file (if available)
6. Raw output / log file (if available)
"""

import os
import json
import zipfile
import datetime
import logging
from typing import List, Optional, Dict, Any
import numpy as np

logger = logging.getLogger(__name__)

from .zmatrix import cartesian_to_zmatrix, format_zmatrix_text
from .chem_identifiers import format_xyz_string
from .qm_log_parser import QMLogParseResult, parse_qm_logfile


def generate_si_latex(
    symbols: List[str],
    coords: np.ndarray,
    summary: Dict[str, Any],
    title: str = "Quantum Chemical Calculation",
) -> str:
    """Generate publication-ready Supporting Information LaTeX snippet for ACS/RSC papers."""
    prog = summary.get("program", "Quantum Chemical Software")
    method = summary.get("method", "DFT")
    basis = summary.get("basis", "def2-TZVP")
    e_ha = summary.get("final_energy_ha")
    e_str = f"{e_ha:.8f}" if e_ha is not None else "N/A"
    zpe = summary.get("zpe_ha")
    zpe_str = f"{zpe:.6f}" if zpe is not None else "N/A"
    g_ha = summary.get("gibbs_ha")
    g_str = f"{g_ha:.8f}" if g_ha is not None else "N/A"

    lines = [
        "% -------------------------------------------------------------",
        f"% Supporting Information Table: {title}",
        f"% Automatically generated by AgyMolden on {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "% -------------------------------------------------------------",
        "\\begin{table}[h!]",
        "\\centering",
        f"\\caption{{Optimized Cartesian coordinates (\\AA) and calculated energetic parameters for {title} calculated at the {method}/{basis} level of theory.}}",
        "\\label{tab:coordinates}",
        "\\small",
        "\\begin{tabular}{lrrr}",
        "\\hline",
        "\\textbf{Atom} & \\textbf{X (\\AA)} & \\textbf{Y (\\AA)} & \\textbf{Z (\\AA)} \\\\",
        "\\hline",
    ]

    for sym, (x, y, z) in zip(symbols, coords):
        lines.append(f"{sym} & {x:12.6f} & {y:12.6f} & {z:12.6f} \\\\")

    lines.extend([
        "\\hline",
        "\\end{tabular}",
        "\\\\[1ex]",
        "\\footnotesize",
        f"\\textbf{{Electronic Energy (\\textit{{E}})}}: {e_str} a.u. \\quad \\textbf{{ZPE}}: {zpe_str} a.u. \\quad \\textbf{{Gibbs Free Energy (\\textit{{G}})}}: {g_str} a.u.",
        "\\end{table}",
        "",
    ])
    return "\n".join(lines)


def generate_si_markdown(
    symbols: List[str],
    coords: np.ndarray,
    summary: Dict[str, Any],
    title: str = "Quantum Chemical Calculation",
    input_text: Optional[str] = None,
) -> str:
    """Generate publication-ready Supporting Information markdown."""
    prog = summary.get("program", "Quantum Chemical Software")
    method = summary.get("method", "DFT")
    basis = summary.get("basis", "def2-TZVP")
    solvent = summary.get("solvation", "gas phase")
    e_ha = summary.get("final_energy_ha")
    e_str = f"{e_ha:.8f} Ha" if e_ha is not None else "N/A"
    homo = summary.get("homo_ev")
    lumo = summary.get("lumo_ev")
    gap = summary.get("gap_ev")
    n_imag = summary.get("n_imaginary_frequencies", 0)
    
    char_str = "local minimum with zero imaginary vibrational frequencies" if n_imag == 0 else f"transition state / higher-order saddle point with {n_imag} imaginary vibrational frequency(ies)"

    md = []
    md.append(f"# Supporting Information: {title}\n")
    md.append(f"*Generated by AgyMolden on {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*\n")
    
    md.append("## 1. Computational Methods\n")
    md.append(
        f"All quantum chemical calculations were performed using the **{prog}** software package. "
        f"Geometries were optimized using the **{method}** theoretical level with the **{basis}** basis set "
        f"in the {solvent}. Harmonic vibrational frequency analyses were computed at the same level of theory "
        f"to confirm each stationary point as a {char_str} and to obtain zero-point vibrational energy "
        f"(ZPE) and thermal corrections at standard temperature (298.15 K) and pressure (1.0 atm) within "
        f"the ideal-gas, rigid-rotor, harmonic oscillator approximation.\n"
    )

    md.append("## 2. Summary of Energetic and Thermochemical Properties\n")
    md.append("| Property | Value (a.u.) | Value (eV / kcal/mol) |")
    md.append("| :--- | :--- | :--- |")
    if e_ha is not None:
        md.append(f"| **Electronic Energy ($E_{{el}}$)** | `{e_ha:.8f} Ha` | `{(e_ha * 27.211386):.4f} eV` |")
    if summary.get("zpe_ha") is not None:
        zpe = summary["zpe_ha"]
        md.append(f"| **Zero-Point Energy (ZPE)** | `{zpe:.6f} Ha` | `{(zpe * 627.5095):.2f} kcal/mol` |")
    if summary.get("enthalpy_ha") is not None:
        h = summary["enthalpy_ha"]
        md.append(f"| **Enthalpy ($H_{{298}}$)** | `{h:.8f} Ha` | `{(h * 627.5095):.2f} kcal/mol` |")
    if summary.get("gibbs_ha") is not None:
        g = summary["gibbs_ha"]
        md.append(f"| **Gibbs Free Energy ($G_{{298}}$)** | `{g:.8f} Ha` | `{(g * 627.5095):.2f} kcal/mol` |")
    if homo is not None and lumo is not None:
        md.append(f"| **HOMO** | `{(homo / 27.211386):.5f} Ha` | `{homo:.3f} eV` |")
        md.append(f"| **LUMO** | `{(lumo / 27.211386):.5f} Ha` | `{lumo:.3f} eV` |")
    if gap is not None:
        md.append(f"| **HOMO–LUMO Gap** | `{(gap / 27.211386):.5f} Ha` | `{gap:.3f} eV` |")
    if summary.get("dipole_debye") is not None:
        md.append(f"| **Dipole Moment** | — | `{summary['dipole_debye']:.3f} Debye` |")
    md.append(f"| **Imaginary Frequencies** | `{n_imag}` | — |")
    md.append("\n")

    freqs = summary.get("frequencies_cm1", [])
    if freqs:
        md.append("### Vibrational Frequencies (cm⁻¹)\n")
        freq_str = ", ".join(f"{f:.1f}" for f in freqs[:15])
        if len(freqs) > 15:
            freq_str += f" ... ({len(freqs)} modes total)"
        md.append(f"`{freq_str}`\n\n")

    md.append("## 3. Cartesian Coordinates (Å)\n")
    md.append(f"Total atoms: `{len(symbols)}`\n")
    md.append("| Index | Element | X (Å) | Y (Å) | Z (Å) |")
    md.append("| :---: | :---: | :---: | :---: | :---: |")
    for idx, (sym, (x, y, z)) in enumerate(zip(symbols, coords), start=1):
        md.append(f"| {idx} | {sym} | {x:12.6f} | {y:12.6f} | {z:12.6f} |")
    md.append("\n")

    if input_text:
        md.append("## 4. Input File\n")
        md.append("```\n" + input_text.strip() + "\n```\n")

    return "\n".join(md)


def create_reproducibility_bundle(
    output_archive_path: str,
    symbols: List[str],
    coords: np.ndarray,
    log_result: Optional[QMLogParseResult] = None,
    log_file_path: Optional[str] = None,
    input_file_path: Optional[str] = None,
    job_title: str = "Molecule",
    extra_metadata: Optional[Dict[str, Any]] = None,
) -> str:
    """
    Export all relevant computational chemistry files into a portable Supporting Information ZIP archive.
    
    Returns the absolute path of the created ZIP archive.
    """
    output_archive_path = os.path.abspath(output_archive_path)
    os.makedirs(os.path.dirname(output_archive_path), exist_ok=True)

    coords_arr = np.array(coords, dtype=float)
    if coords_arr.ndim != 2 or coords_arr.shape[1] != 3:
        raise ValueError(f"Expected coords shape (N, 3), got {coords_arr.shape}")

    # Build summary dict
    summary: Dict[str, Any] = {
        "title": job_title,
        "n_atoms": len(symbols),
        "formula": "".join(f"{s}{symbols.count(s) if symbols.count(s) > 1 else ''}" for s in sorted(set(symbols))),
        "export_date": datetime.datetime.now().isoformat(),
        "agymolden_version": "2.0.0",
    }

    if extra_metadata:
        summary.update(extra_metadata)

    if log_result:
        final_e = log_result.trajectory_energies[-1] if log_result.trajectory_energies else None
        freqs = list(log_result.vibrational_analysis.frequencies) if (log_result.vibrational_analysis and getattr(log_result.vibrational_analysis, "frequencies", None) is not None) else []
        gap_ev = (log_result.lumo_ev - log_result.homo_ev) if (log_result.homo_ev is not None and log_result.lumo_ev is not None) else None
        n_imag = len([f for f in freqs if f < -1.0])

        summary.update({
            "program": log_result.program_name or "QM Program",
            "converged": log_result.converged,
            "final_energy_ha": final_e,
            "homo_ev": log_result.homo_ev,
            "lumo_ev": log_result.lumo_ev,
            "gap_ev": gap_ev,
            "dipole_debye": log_result.dipole_debye,
            "zpe_ha": log_result.zpe_ha,
            "enthalpy_ha": log_result.enthalpy_ha,
            "gibbs_ha": log_result.gibbs_ha,
            "frequencies_cm1": freqs,
            "n_imaginary_frequencies": n_imag,
            "is_irc": log_result.is_irc,
        })
    else:
        summary.setdefault("program", "AgyMolden Modeling Environment")

    # Generate XYZ
    xyz_comment = f"{job_title} | E = {summary.get('final_energy_ha', 'N/A')} Ha | Generated by AgyMolden"
    xyz_content = format_xyz_string(symbols, coords_arr, comment=xyz_comment)

    # Generate Z-Matrix
    try:
        zatoms = cartesian_to_zmatrix(symbols, coords_arr)
        zmat_content = format_zmatrix_text(zatoms, numeric=True)
    except Exception:
        zmat_content = "# Z-Matrix generation skipped (incompatible geometry topology)\n"

    # Input text if available
    input_text = None
    if input_file_path and os.path.isfile(input_file_path):
        try:
            with open(input_file_path, "r", encoding="utf-8", errors="ignore") as f:
                input_text = f.read()
        except OSError as e:
            logger.warning("Could not read input file for SI bundle %s: %s", input_file_path, e)

    # Generate Markdown Supporting Info
    si_markdown = generate_si_markdown(
        symbols=symbols,
        coords=coords_arr,
        summary=summary,
        title=job_title,
        input_text=input_text,
    )

    # Generate LaTeX Supporting Info
    si_latex = generate_si_latex(
        symbols=symbols,
        coords=coords_arr,
        summary=summary,
        title=job_title,
    )

    # Assemble ZIP file
    with zipfile.ZipFile(output_archive_path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("GEOMETRY.xyz", xyz_content)
        zf.writestr("GEOMETRY.zmat", zmat_content)
        zf.writestr("CALCULATION_SUMMARY.json", json.dumps(summary, indent=2))
        zf.writestr("COMPUTATIONAL_DETAILS.md", si_markdown)
        zf.writestr("SUPPORTING_INFO_TABLE.tex", si_latex)

        if input_file_path and os.path.isfile(input_file_path):
            base_in = os.path.basename(input_file_path)
            zf.write(input_file_path, arcname=f"input/{base_in}")

        if log_file_path and os.path.isfile(log_file_path):
            base_log = os.path.basename(log_file_path)
            zf.write(log_file_path, arcname=f"output/{base_log}")

    return output_archive_path
